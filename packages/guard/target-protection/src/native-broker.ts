/** Trusted SDK broker; its host must own the broker and every SDK descendant before this code starts. @module */
import { randomUUID } from 'node:crypto'
import { extname } from 'node:path'
import type { Readable, Writable } from 'node:stream'
import { fileURLToPath } from 'node:url'
import { inspect } from 'node:util'
import type { ContainerRequest, ProbeFacts } from '@microsoft/mxc-sdk/v1'
import { attachObservedWindowsJob, buildCommandLine, observedWindowsBootstrapPath } from '@deepseek-ai/dsh-win32-process'
import type { ObservedWindowsJob } from '@deepseek-ai/dsh-win32-process'
import { readNativeBootstrapIdentity } from './native-bootstrap.ts'
import { nativeBrokerConfigSchema, type NativeBrokerConfig } from './native-broker-config.ts'
import { requireNativeRuntime } from './native-runtime.ts'
import { NATIVE_FRAME, NativeProtocolError, readNativeFrames, writeNativeBytes, writeNativeFrame } from './native-protocol.ts'
import { startNativeIngress, type NativeIngressLease, type NativeIngressOptions } from './native-ingress.ts'

/** SDK process surface consumed by the broker; final physical closure is observed by the host's outer Job. */
export interface NativeBrokerChild {
  readonly id: number
  readonly standardInput: Writable | null
  readonly standardOutput: Readable | null
  readonly standardError: Readable | null
  wait(): Promise<{ exitCode: number; timedOut: boolean }>
  kill(): void
  dispose(): void
}

/** Strict backend probe and spawn operations; injected tests do not load native platform libraries. */
export interface NativeBrokerSdk {
  probe: (request: ContainerRequest) => {
    tier?: string
    needsDaclAugmentation?: boolean
    probes: Pick<ProbeFacts, 'baseContainerSupportsDenyPaths' | 'baseContainerSupportsEnumeratePaths' | 'baseContainerSupportsIdentitylessLoopbackProxy'>
  }
  spawn: (request: ContainerRequest, options: { telemetry: { enabled: false } }) => Promise<NativeBrokerChild>
}

/**
 * Construct the fixed worker invocation and containment policy from owner-validated configuration.
 * @param config - Exact file policy, private temporary root, optional protected local gateway and timing.
 * @param nonce - Per-start identity token generated by the broker.
 * @param environment - Broker environment; only system paths and Electron Node mode can reach the bootstrap.
 * @returns A BaseContainer request with no direct network egress or target-controlled startup hooks.
 */
export function nativeContainerRequest(
  config: NativeBrokerConfig, nonce: string, environment: NodeJS.ProcessEnv = process.env,
): ContainerRequest {
  const source = extname(fileURLToPath(import.meta.url)) === '.ts'
  /* v8 ignore next -- The emitted worker path is exercised by the built native-broker smoke. */
  const entry = new URL(source ? './native-worker.ts' : './native-worker.js', import.meta.url)
  /* v8 ignore next -- The built smoke verifies that no source hook is loaded. */
  const hook = source ? import.meta.resolve('tsx/esm/api') : ''
  /* v8 ignore next -- Compiled workers do not read a source tsconfig. */
  const tsconfig = source ? fileURLToPath(new URL('../../../../tsconfig.base.json', import.meta.url)) : ''
  const args = [observedWindowsBootstrapPath(), nonce, entry.href, hook, tsconfig, config.temporaryRoot]
  return {
    command: buildCommandLine(process.execPath, args), workingDirectory: config.cwd,
    containment: { type: 'processcontainer', config: { filesystem: { enumeratePaths: config.files.enumeratePaths } } },
    filesystem: { readonlyPaths: config.files.readonlyPaths, readwritePaths: config.files.readwritePaths,
      deniedPaths: config.files.deniedPaths },
    network: {
      egress: { default: 'deny' },
      // MXC's identityless proxy requires ingress admission; this does not establish inbound peer isolation.
      ingress: { default: config.proxyUrl === null ? 'deny' : 'allow', hostLoopback: config.proxyUrl === null ? 'deny' : 'allow' },
      ...config.proxyUrl === null ? {} : { runtimeConfig: { networkProxy: config.proxyUrl } },
    },
    ui: { disable: false, clipboard: 'none', allowInputInjection: false }, timeoutMs: config.timeoutMs,
    environment: {
      SystemRoot: environment.SystemRoot, WINDIR: environment.WINDIR, SystemDrive: environment.SystemDrive,
      TEMP: config.temporaryRoot, TMP: config.temporaryRoot, LOCALAPPDATA: config.temporaryRoot, USERPROFILE: config.temporaryRoot,
      ...environment.ELECTRON_RUN_AS_NODE === '1' ? { ELECTRON_RUN_AS_NODE: '1' } : {},
    },
  }
}

/* v8 ignore start -- Real source/built broker processes exercise SDK loading; prerequisite decisions are tested separately. */
async function loadSdk(): Promise<NativeBrokerSdk> {
  requireNativeRuntime(process.platform, process.versions.node, 'pkg' in process)
  return import('@microsoft/mxc-sdk/v1')
}
/* v8 ignore stop */

/**
 * Bridge the trusted host to one contained worker without treating SDK completion as physical process-range proof.
 * @param input - Host control pipe; the first frame must configure this invocation.
 * @param output - Framed target streams and lifecycle messages.
 * @param diagnostics - SDK/bootstrap diagnostics, separate from target stderr.
 * @param sdkLoader - SDK loader; portable tests inject a transport implementation.
 * @returns After SDK and streams settle. The outer host must still terminate/join its whole broker range.
 */
export async function runNativeBroker(
  input: Readable, output: Writable, diagnostics: Writable, sdkLoader: () => Promise<NativeBrokerSdk> = loadSdk,
): Promise<void> {
  const messages = readNativeFrames(input)
  const tasks: Promise<unknown>[] = []
  const abort = new AbortController()
  let child: NativeBrokerChild | undefined, failure: unknown
  let ingressJob: ObservedWindowsJob | undefined, ingress: NativeIngressLease | undefined, ingressOptions: NativeIngressOptions | undefined
  let nativeInput: Writable | null = null, nativeOutput: Readable | null = null, nativeError: Readable | null = null
  const state = { finished: false, failureReported: false }
  const fail = (error: unknown): void => {
    failure ??= error
    abort.abort(error); input.destroy()
    try { child?.kill() } catch (killError) { failure = new AggregateError([failure, killError], 'Native broker termination failed') }
    try { ingressJob?.terminate(1) } catch (killError) { failure = new AggregateError([failure, killError], 'Native ingress range termination failed') }
  }
  const closed = (): void => { if (!state.finished) fail(new NativeProtocolError('Native broker output closed.')) }
  const observe = (task: Promise<unknown>): void => { tasks.push(task); void task.catch(fail) }
  output.on('error', fail); output.once('close', closed); diagnostics.on('error', fail)
  try {
    const first = await messages.next()
    if (first.done || first.value.tag !== NATIVE_FRAME.configure) throw new NativeProtocolError('Native broker configuration is required.')
    const parsed = nativeBrokerConfigSchema.safeParse(JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(first.value.data)))
    if (!parsed.success) throw new NativeProtocolError('Invalid native broker configuration.')
    const config = parsed.data, nonce = randomUUID(), request = nativeContainerRequest(config, nonce)
    const sdk = await sdkLoader(), support = sdk.probe(request)
    if (support.tier !== 'base-container' || support.needsDaclAugmentation !== false
      || !support.probes.baseContainerSupportsDenyPaths || !support.probes.baseContainerSupportsEnumeratePaths
      || config.proxyUrl !== null && !support.probes.baseContainerSupportsIdentitylessLoopbackProxy) {
      throw new NativeProtocolError('Required native containment capabilities are unavailable.')
    }
    abort.signal.throwIfAborted()
    child = await sdk.spawn(request, { telemetry: { enabled: false } })
    const native = child, stdin = native.standardInput, stdout = native.standardOutput, stderr = native.standardError
    nativeInput = stdin; nativeOutput = stdout; nativeError = stderr
    if (stdin === null || stdout === null || stderr === null) throw new NativeProtocolError('Native broker transport is incomplete.')
    stdin.on('error', fail)
    const nativeExited = native.wait()
    observe(nativeExited)
    observe((async () => {
      for await (const chunk of stderr as AsyncIterable<Uint8Array>) await writeNativeBytes(diagnostics, chunk)
    })())
    const startup = AbortSignal.any([abort.signal, AbortSignal.timeout(config.startupTimeoutMs)])
    const identity = await readNativeBootstrapIdentity(stdout, nonce, native.id, startup)
    if (config.ingress !== undefined) {
      ingressOptions = config.ingress
      ingressJob = attachObservedWindowsJob(identity)
      ingress = await startNativeIngress(config.ingress, ingressJob, identity, abort.signal)
      void ingress.failed.catch(fail)
    }
    startup.throwIfAborted()
    abort.signal.throwIfAborted()
    await writeNativeBytes(stdin, Uint8Array.of(1))
    let rangeExited = false
    const receive = (async () => {
      for await (const frame of readNativeFrames(stdout)) {
        const allowed: number[] = [NATIVE_FRAME.stdout, NATIVE_FRAME.stderr, NATIVE_FRAME.controlOutput, NATIVE_FRAME.accepted,
          NATIVE_FRAME.exited, NATIVE_FRAME.failed, NATIVE_FRAME.streamClosed, NATIVE_FRAME.rangeExited]
        if (!allowed.includes(frame.tag)) {
          throw new NativeProtocolError('Unexpected native worker response.')
        }
        if (frame.tag === NATIVE_FRAME.rangeExited) rangeExited = true
        if (frame.tag === NATIVE_FRAME.failed) state.failureReported = true
        await writeNativeFrame(output, frame)
      }
      const result = await nativeExited
      if (result.exitCode !== 0 || result.timedOut || !rangeExited) throw new NativeProtocolError('Native worker did not confirm completion.')
      state.finished = true; input.destroy()
    })()
    observe(receive)
    try {
      for await (const frame of messages) {
        if (state.finished) break
        const allowed: number[] = [NATIVE_FRAME.launch, NATIVE_FRAME.stdin, NATIVE_FRAME.stdinEnd, NATIVE_FRAME.control,
          NATIVE_FRAME.controlEnd, NATIVE_FRAME.terminate]
        if (!allowed.includes(frame.tag)) throw new NativeProtocolError('Unexpected host command frame.')
        await writeNativeFrame(stdin, frame)
      }
    } catch (error) { if (!state.finished || failure !== undefined) throw error }
    if (!state.finished) throw new NativeProtocolError('Native broker input ended before completion.')
    await Promise.all(tasks)
    if (failure !== undefined) throw new Error('Native broker transport failed.', { cause: failure })
  } catch (error) {
    fail(error)
    try {
      await writeNativeBytes(diagnostics, Buffer.from(`${inspect(error, { depth: 3 })}\n`))
      if (!state.failureReported) await writeNativeFrame(output, { tag: NATIVE_FRAME.failed, data: Buffer.from('{"code":"NATIVE_BROKER_FAILED"}') })
    }
    catch (reportError) { throw new AggregateError([failure, reportError], 'Native broker and error reporting failed') }
    throw new Error('Native broker failed.', { cause: failure })
  } finally {
    input.destroy()
    try {
      if (child !== undefined) {
        try {
          if (!state.finished) child.kill()
          nativeInput?.destroy(); nativeOutput?.destroy(); nativeError?.destroy()
          await child.wait()
        } finally { child.dispose() }
      }
    } finally {
      try {
        if (ingressJob !== undefined && ingressOptions !== undefined) {
          if (!state.finished) ingressJob.terminate(1)
          if (!await ingressJob.waitForExit(ingressOptions.pollIntervalMs, AbortSignal.timeout(ingressOptions.shutdownTimeoutMs))) {
            throw new NativeProtocolError('Native ingress range shutdown remains unconfirmed; retain its rules.')
          }
          try { await ingress?.release() } finally { ingressJob.close() }
        }
      } finally {
        await Promise.allSettled([...tasks, messages.return(undefined)])
        output.off('error', fail); output.off('close', closed); diagnostics.off('error', fail)
      }
    }
  }
}
